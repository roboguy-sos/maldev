KEY_INPUT = bytes(range(32))
AES_KEY   = hashlib.sha256(KEY_INPUT).digest()

def encrypt(plaintext: bytes, key: bytes) -> bytes:
    if len(key) != 32:
        raise ValueError("AES-256 requires a 32-byte key")
    nonce = os.urandom(12)
    aes = AESGCM(key)
    ciphertext_and_tag = aes.encrypt(nonce, plaintext, None)
    return nonce + ciphertext_and_tag

def emit_header(path, blob, key_input):
    with open(path, "w") as f:
        f.write("#pragma once\n")
        f.write("static const unsigned char g_Key[32] = { %s };\n"
                % ",".join(f"0x{b:02X}" for b in key_input))
        f.write("static const unsigned char enc_pay[] = {\n")
        for i in range(0, len(blob), 16):
            f.write("    " + ",".join(f"0x{b:02X}" for b in blob[i:i+16]) + ",\n")
        f.write("};\n")
        f.write(f"static const unsigned int enc_pay_len = {len(blob)};\n")

