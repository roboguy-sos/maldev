import sys, os

SEED = 5
KEY  = 0x69
HERE = os.path.dirname(os.path.abspath(__file__))

def djb2a(s):
    h = KEY
    for c in s.encode("ascii"):
        h = ((h << SEED) + h + c) & 0xFFFFFFFF
    return h

def djb2w(s):
    h = KEY
    for c in s.encode("utf-16-le"):
        h = ((h << SEED) + h + c) & 0xFFFFFFFF
    return h

APIS = [
    ("NtAllocateVirtualMemory", "Sc0", "wNTAVM", "sysAddrNTAVM"),
    ("NtWriteVirtualMemory",    "Sc1", "wNTWVM", "sysAddrNTWVM"),
    ("NtProtectVirtualMemory",  "Sc2", "wNTPVM", "sysAddrNTPVM"),
    ("NtCreateThreadEx",        "Sc3", "wNTCTE", "sysAddrNTCTE"),
]

def main():
    path = os.path.join(HERE, "resource.asm")
   

    with open(path, "w") as f:
        f.write("; AUTO-GENERATED by hashgen.py - do not edit\n")
        f.write(f"HASH_SEED EQU {SEED}\n")
        f.write(f"HASH_KEY  EQU 0{KEY:02X}h\n\n")

        # Hash constants
        for api, _, _, _ in APIS:
            f.write(f"{api}_HASH EQU 0{djb2a(api):08X}h\n")
        f.write(f"ntdll_HASH EQU 0{djb2w('ntdll.dll'):08X}h\n\n")

        # EXTERNs for the SSN + syscall-address globals
        for _, _, ssn, addr in APIS:
            f.write(f"EXTERN {ssn}:DWORD\n")
            f.write(f"EXTERN {addr}:QWORD\n")
        f.write("\n")

        # PUBLIC stub labels
        for _, stub, _, _ in APIS:
            f.write(f"PUBLIC {stub}\n")
        f.write("\n.code\n")

        # Stub bodies
        for _, stub, ssn, addr in APIS:
            f.write(f"{stub} PROC\n")
            f.write("    mov r10, rcx\n")
            f.write(f"    mov eax, {ssn}\n")
            f.write(f"    jmp QWORD PTR [{addr}]\n")
            f.write(f"{stub} ENDP\n\n")

        f.write("end\n")

if __name__ == "__main__":
    try:
        main()
    except Exception:
        import traceback
        traceback.print_exc()
        sys.exit(1)